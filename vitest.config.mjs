/* ============================================================
 * vitest.config.mjs — 测试发现范围 + 超时口径（**唯一真源**）
 * ------------------------------------------------------------
 * 理由一 —— 测试发现范围：**`.review/` 会被 vitest 默认收集**。
 *
 * 实测：往 `.review/` 放一个 `*.test.js`（本工程把它当"工作产物区"，见 SKILL.md 顶部落盘规矩），
 * `npm test` 会**直接变红** —— 因为 vitest 默认的 include 是 `**\/*.test.js`，
 * 而默认 exclude 只有 `**\/node_modules/**` 与 `**\/.git/**`。
 *
 * 为什么这件事值得一个配置文件：
 *   `.review/` 是**允许随时删、允许放临时脚本与备份**的地方。一个"把备份放进去就红"的测试套件，
 *   会让人得出错误结论（"我改坏了什么"），而真实原因只是**一个不该被收集的目录**。
 *   本工程已有过同型的坑：`.review/` 在工作产物口径之外、却在 vitest 的 collect 之内 ——
 *   **两个口径不一致**，而它只在踩到时才可见。
 *
 * 理由二 —— 超时口径：**整个套件只有一个数字，且只在这里写一次**（本批从"逐文件打补丁"收敛而来）。
 *
 * 本工程已三次踩到同一形状：某个用例在负载下越过超时线，报文是 `Test timed out in Nms`（是超时，
 * **不是断言失败** —— 报文里没有"期望/实际"），而它测的东西其实是对的：
 *   · 2026-10-12，框架默认 5000ms 下：`tests/doc-import.test.js` 的 PDF 书签切片、`tests/dsh-ask.test.js`
 *     的 `--dry-run`、`tests/mcp-protocol.test.js` 的 isError 一拍、`tests/verify-budget.test.js` 的
 *     `gitCommitCount` 这 4 条偶发红。三条读数：① 这 4 个文件**单独跑全绿**（4 files / 110 tests /
 *     6.13s / exit 0）；② 默认并行池下 `npm test` 连红 3/3，红的永远是这同一组用例，而其中
 *     `gitCommitCount` **只 spawn 一个 `git`**、与任何业务改动无关（当时本机另有 7 electron + 13 node）；
 *     ③ 限池（`--pool=threads --maxWorkers=4`）下 62 files / 1206 tests 全绿（28.0s）。
 *     ⇒ 定性为**环境/负载脆弱性**（默认池 + 机器负载下，spawn 到出结果超过 5s），**不是逻辑失败**；
 *       当时把它抬到 15s —— 但那个数只按当时那几条的量级定，**没按套件里最贵的用例定**（见下）。
 *   · 之后 `tests/dsh-embedded-overrides.test.js`（用例会 spawn 子进程，实测抓到 5087 ms 的那次失败）
 *     与 `tests/w8-dry-run.test.js`（A1 = 58 次进程内命令 + 4 次整棵沙箱树快照）各自又在**文件里**
 *     写了一份 `vi.setConfig({ testTimeout: 30000 })` —— 同一事实的第二、第三处表达，本批收回到这里。
 *
 * 这个数字按**套件里最贵的那条用例**定，不按典型用例定（这是本批的核心判断）：
 * 单测超时的职责只是区分"慢"与"错"，而任何按"典型用例"定的上限都必然让最贵的用例余量不足
 * ⇒ 同类偶发红会一直复发。实测（2026-10-13，全量同池、本机另有 9 node + 7 electron 进程）全库最慢三条：
 *   · `tests/w8-dry-run.test.js` 的 A1 = **11129 ms**（旧口径 15000 ms 只剩 **1.35×** ⇒ 已贴线）
 *   · `tests/doc-import.test.js` 的"PDF 响亮拒绝" = **4932 ms**（旧口径剩 3.0×）
 *   · `tests/search-fuzzy.test.js` 的 MCP 透传 = **3591 ms**（旧口径剩 4.2×）
 * ⇒ 30000 ms：给最贵的那条留 **2.7×**、给其余 ≥ **6.0×**。而且它不是新数字 —— 30 s 本来就是本工程给
 *   "慢文件"用的那个数，本批只是把它升格成**唯一**的一个（顺带消掉上面那两处文件级副本）。
 *
 * ⚠️ 超时**不是**放宽断言的借口（这条没变）：它只用来区分"慢"与"错"；30s 仍不出结果 = 真的卡住 ⇒ 照样红。
 * ⚠️ 单一口径的票面价，如实记：一个**真卡住**的用例现在 30s 才报（从前 15s）= "坏信号晚 15s 到"。
 *   性能**不靠**这里管：该管它的是 `npm run verify` 的步预算（`scripts/verify.js` 第 9 步 G3 单元测试
 *   = 60000 ms 的止涨线）；单测只管"对不对" ✓。
 * ⚠️ 留账（本批**没动**）：`tests/doc-import.test.js` 有两条重度用例自带 per-test 的 30 s
 *   （`it(name, fn, 30000)`）⇒ 当前与本口径同值；口径若再变，它就是第二处会漂的表达，届时删掉即可。
 *
 * 为什么用 `.mjs`：本工程的测试层本来就是 ESM（`tests/*.test.js` 用 `import`），
 * 与它保持一致；且 ESM 的 `import { configDefaults }` 是 vitest 官方推荐的写法。
 *
 * ⚠️ 改这里要连带：`scripts/docs-registry-check.js` 的 `ROOT_FILES` 白名单（G8 管工程根文件），
 * 否则新对话跑门禁会红。该白名单的作用正是"工程根只允收入口文档与工程配置文件"。
 * ============================================================ */
import { configDefaults, defineConfig } from 'vitest/config';

export default defineConfig({
  test: {
    // 保留 vitest 的默认排除项（显式列出，避免"以为它会自动带"），再补上工作产物区。
    exclude: [
      ...configDefaults.exclude,
      '**/.review/**'
    ],
    // 理由二：这**一个**数字是整个套件的唯一超时口径（测试文件里不再各写一份）。
    // 30 s 按"最贵的那条用例"定：给全库最慢的 w8 A1（负载下实测 11129 ms）留 2.7×，其余 ≥ 6.0×。
    // 它只区分"慢"与"错"，**不动 pool 配置**（并发口径保持默认）；真卡住 30 s 照样红。
    // 两个字段同一个口径（都是"多久不出结果算卡住"），所以一起动。
    testTimeout: 30000,
    hookTimeout: 30000
  }
});
