/* ================= 冒烟「严格档」开关的解析（纯函数，零副作用 ⇒ 可被单测引入 ✓） =================
 * 环境变量只有一个名字：`MM_SMOKE_CLIP_STRICT`（名字的来历：域 39 的剪贴板判据是最先吃三态、
 * 也是"环境坏会把真回归洗成未验证"这个盲区第一次被看见的地方；它管的是**所有**域的第三态）。
 * 接受的值**只有下面这几种**，别的**当场报错**（让调用方 exit 1，不许静默落回某一档）：
 *   · 未设 / `undefined` / `null` ⇒ **关（默认）**，且**一条额外输出都不打** ⇒ 与加这个开关之前逐字节相同 ✓
 *   · `0` / `false` ⇒ 关（显式关：与默认档走同一条路径，也不打额外输出）
 *   · `1` / `true` / 空串（**裸写**：`bash` 里 `MM_SMOKE_CLIP_STRICT= npm run smoke` 拿到的就是空串）⇒ 开
 *   · 其它（`nonsense` / `yes` / `2` / `True` …）⇒ `{ok:false}` ⇒ 调用方**当场报错 + exit 1**
 * 为什么把值收窄（照 `src/item-index.js` 的 `parseFlag` 先例）：一个写错的开关值若被静默当成 false，
 * "我这一轮真的在严格档里跑"就永远不成立 —— 而这正是**没人会去核对**的那一类静默失效 ✗。
 * @param {string|boolean|undefined|null} raw 环境变量的原值（**由调用方读**：本函数不碰 `process.env` ✓）
 * @returns {{ok:boolean, strict:boolean, reason:string}}
 */
module.exports.parseStrictEnv = function parseStrictEnv(raw) {
  if (raw === undefined || raw === null) return { ok: true, strict: false, reason: '' };
  if (raw === true || raw === '' || raw === '1' || raw === 'true') return { ok: true, strict: true, reason: '' };
  if (raw === false || raw === '0' || raw === 'false') return { ok: true, strict: false, reason: '' };
  return { ok: false, strict: false,
    reason: '只能是 1 / true / 空串（裸写=开）或 0 / false（关），收到 ' + JSON.stringify(String(raw)) };
};

/* ================= 环境准入（G5 之前"拒绝跑"的判据；纯函数，零副作用 ⇒ 可被单测引入 ✓） =================
 * **它补的是 `R1d` 缺的那一半**：`R1d` 管"失败必须响亮"，本条管"**有些失败不该以'跑出来的红'
 * 的形态出现，而该以'拒绝跑'的形态出现**" —— 环境不够时跑出来的红是**假红**，而假红的
 * 下场是连真红也不看（`docs/RULES.md` §2 的旁注有全文；那里的裁决与这里的实现必须一致）。
 *
 * 为什么以前没有：`buildVerifyHistory` 只把 `freeMemMB` **记进** `.review/verify-history.jsonl`
 * （`scripts/verify.js` 那句注释写的是"这三点是同一份代码、结果不同时最先要排除的变量"）——
 * 也就是说内存从来只是一条**旁证**，没有任何判据读它。实测它确实会变：390 条历史记录的
 * `freeMemMB` 从 4345 MB 到 19380 MB（2026-10-20 现算）⇒ "这次的内存和上次不一样"是常态，
 * 但"环境差到**根本不该跑**"这件事一直没有出口，只能眼睁睁看它跑出假红。
 *
 * ## 三档（没实装的档不许写成已实装 —— 照 `docs/RULES.md` §2 那条口径）
 *   ① **准入拒绝**（本函数 `admitted:false`）：可用内存 < 门槛 ⇒ 调用方**一条断言都不跑**、
 *      **不算通过**、**exit 非 0**（响亮，`R1d` ①）。
 *   ② **降级继续**（**不在本函数里**）：`scripts/smoke/real-write-guard.js` 的"另一个活着的
 *      界面实例正在写真实目录"属于这一档 —— 它是本机最普通的情形，**不许**升级成准入拒绝
 *      （那会把门禁变成长期红而被关掉，`M1`）。本函数只管 ①，别把两件事混在一起。
 *   ③ **采不到真值 = 拒绝**（`ok:false`）：可用内存取不到（非有限正数）⇒ 按红处理，
 *      不许当成"环境没问题"放行 —— 与 `docs/RULES.md` §2「采不到真值 = 红」同源。
 *
 * ## 门槛为什么是这个数（如实标注它的证据强度，别当它是标定过的）
 *   默认门槛写在 `ENV_ADMISSION.minFreeMemMB`，**`docs/RULES.md` 不抄这个数**（抄一份就会漂；
 *   门禁每次运行都把"门槛 + 现读数 + 放行/拒绝"打印出来）。选它的依据只有两条，都有据可查：
 *     · 390 条验证历史里 `freeMemMB` 的**最小值是 4345 MB** ⇒ 默认门槛低于它，
 *       不会在"这台机器一向的运行状态"下误拒（误拒的代价 = 把愿意跑验证的人挡在门外）；
 *     · `main.js` 里记过的真实事故：反复跑把整机提交内存推到 80%，连带把同机其它界面拖卡/拖崩
 *       ⇒ 内存确实会到"跑出来的红不算数"的程度。
 *   ⚠️ 它是**护栏，不是标定值**：没有人在"内存刚好不够"那一刻测到过阈值（也没有那个读数），
 *   所以不许拿它去做更细的判断（例如"这次慢了是因为内存"）。要动它 = 动 `ENV_ADMISSION`，
 *   并在 `CHANGELOG.md` 留一笔。
 *
 * ## ⚠️ 2026-10-20 订正：原门槛 1024 MB **形同虚设**，已抬到 3072
 *   上线当天做了实测采样（独占、G5 full 档、每 12 s 一次）：
 *     · Electron 全家 **合计工作集 1513 → 4525 MB**，**单个进程峰值 2445 MB**；
 *     · 整机空闲从 **7223 MB 掉到 4446 MB** ⇒ **G5 这一段本身要吃约 2.7 GB**。
 *   ⇒ 空闲只剩 1024 MB 时放行 ⇒ 必然跑成假红/超时，**门槛设在它保护不了的位置**。
 *   原 1024 的选法只回答了"**不会误拒**"（4345 的最小值确实远高于它），**没回答"能不能拦住"**。
 *   新值 **3072** 的依据是双向的：
 *     · 下界（能拦住）：G5 边际需求约 2.7 GB ⇒ 门槛必须高于它；
 *     · 上界（不误拒）：历史最小值 4345 MB ⇒ 3072 仍低于它，正常状态不会被挡。
 *   ⚠️ 3072 仍是**护栏**，不是"测出来刚好够"的数 —— 见上面那段"别当它是标定值"。
 */
const ENV_ADMISSION = Object.freeze({
  /** G5（唯一真起 Electron 的步骤）的可用内存门槛（MB）。**本文件是它的唯一权威** */
  minFreeMemMB: 3072,
  /** 覆盖门槛的开关名（值必须是正整数；非法 ⇒ 当场红，不许静默落回默认值） */
  minVar: 'MM_MIN_FREE_MEM_MB',
  /** 拒绝时的退出码（**与产品红的 1 区分开**："没跑"与"跑了但失败"不是一件事） */
  refusedExitCode: 3
});

module.exports.ENV_ADMISSION = ENV_ADMISSION;

/**
 * 判"这一轮的环境准不准跑 G5"。
 *
 * **纯函数**：`os.freemem()` 与 `process.env` 一律由调用方现取后传进来（本函数不碰它们 ⇒
 * 可以用固定输入做单测与判别力证明，也不会在 require 时就结账）。
 *
 * @param {{freeMB:number, rawMin?:string|number|null}} input
 *   `freeMB` = 当前可用物理内存（MB）；`rawMin` = 覆盖门槛的原始值（未设传 `undefined`/`null`）
 * @returns {{ok:boolean, admitted:boolean, freeMB:number|null, minMB:number, reason:string, override:boolean}}
 *   `ok:false` ⇒ **判据本身没成立**（采不到可用内存 / 开关值非法）⇒ 调用方必须**红**，
 *     不许把它当"放行"或"跳过"（`ok:false` 时 `admitted` 恒为 false）；
 *   `ok:true, admitted:false` ⇒ **准入拒绝**（环境不够，跑出来只会是假红）；
 *   `ok:true, admitted:true` ⇒ 放行，且**调用方必须打印** `freeMB` 与 `minMB`（门槛被改小过要看得见）。
 */
module.exports.checkEnvAdmission = function checkEnvAdmission(input) {
  const inp = input || {};
  const rawMin = inp.rawMin;
  let minMB = ENV_ADMISSION.minFreeMemMB;
  let override = false;
  const ret = (ok, admitted, freeMB, reason) => ({
    ok: ok, admitted: !!ok && admitted, freeMB: freeMB === undefined ? null : freeMB,
    minMB: minMB, reason: reason || '', override: override
  });

  // ① 开关值：**只有**"未设"或"正整数"两种合法形状。写错的值不许静默落回默认门槛
  //    （照 `parseStrictEnv` 的先例：开关写错的后果是"你以为门槛生效了，其实没有"）。
  if (rawMin !== undefined && rawMin !== null && String(rawMin).trim() !== '') {
    const n = Number(String(rawMin).trim());
    if (!isFinite(n) || !Number.isInteger(n) || n <= 0) {
      return ret(false, false, inp.freeMB,
        ENV_ADMISSION.minVar + ' 必须是正整数（MB），收到 ' + JSON.stringify(String(rawMin)));
    }
    minMB = n;
    override = true;
  }

  // ② 可用内存取不到 ⇒ **采不到真值 = 拒绝**（不许当成"环境没问题"）
  const freeMB = Number(inp.freeMB);
  if (!isFinite(freeMB) || freeMB <= 0) {
    return ret(false, false, null,
      '取不到可用物理内存（os.freemem() 返回 ' + JSON.stringify(inp.freeMB) + '）⇒ 采不到真值 = 拒绝放行');
  }

  // ③ 判据
  if (freeMB < minMB) {
    return ret(true, false, Math.round(freeMB),
      '可用内存 ' + Math.round(freeMB) + ' MB < 门槛 ' + minMB + ' MB'
        + (override ? '（门槛由 ' + ENV_ADMISSION.minVar + ' 覆盖）' : '（默认门槛）'));
  }
  return ret(true, true, Math.round(freeMB), '');
};

/* ================= 冒烟结果的**三态计数**（纯函数，零副作用 ⇒ 可被单测引入 ✓） =================
 * 为什么需要第三档（真实形状，2026-10-12）：域 39 的剪贴板判据在本机**稳定红**，
 * 而根因是**环境**（系统剪贴板不可用：主进程写后回读为空，同机 `Get-Clipboard` 与
 * `[System.Windows.Forms.Clipboard]::GetText()` 两个独立 API 也全都失败）。这种红既不是产品缺陷，
 * 也不该静默当通过 —— 它把全链按在 13/14 连着好几批，而两边都是错的答案。
 * 口径（照第八批"撕裂快照指纹采不到"那一档）：**采不到真值 ⇒ 响亮说"本项未验证"、不计入、不阻断**。
 *
 * 三档 = { 通过, 失败, 未验证 }（`B4c`：数数型判据也要数清"能输出几种判定"）：
 *   · `ok:true` 且**没有** `unverified` ⇒ 通过（进分子分母）；
 *   · `ok:true` 且**有** `unverified`   ⇒ **未验证**（两个数都不进！只进第三个计数）；
 *   · `ok:false`（哪怕同时带了 `unverified`）⇒ **失败** —— **fail-safe**：`unverified` 只允许出现在
 *     通过的结果上；一条结果既说"未验证"又说"失败"时**按失败计**，绝不能让"未验证"变成掩盖真失败的后门
 *     （本工程最重的损害类别："没做，却看不出没做"）。
 *
 * **严格档**（`opts.strict`，对应环境变量 `MM_SMOKE_CLIP_STRICT`，默认关）：`unverified` 那一档
 * 从"两个数都不进"改成"**进失败**"（`failed` +1、`total` +1、`unverified` 照样单独计数并列出原因）
 * —— 这就是"宁可红，不许悄悄放过"。两档用的是**同一个函数**，不许在别处再算一份（`B1`）。
 * ⚠️ 默认档（`opts` 不给 / `strict` 假）**一个字节都不许变**：它是既有口径，改了就是改读数。
 *
 * @param {Array<{ok?:boolean, unverified?:string}>} results
 * @param {{strict?:boolean}} [opts] 不给 ⇒ 默认档（未验证不进通过/总数，见上面口径）
 * @returns {{passed:number, failed:number, unverified:number, total:number, unverifiedList:string[]}}
 *   `total` = **参与计数**的条数（= passed + failed）；默认档**不含**未验证，严格档**含**（它已进 failed）；
 *   `unverifiedList` 给"响亮行"用（**两档都照列**：严格档也要看得见"是哪几条、为什么"）。
 */
module.exports.tally = function tally(results, opts) {
  const strict = !!(opts && opts.strict);
  const list = Array.isArray(results) ? results : [];
  let passed = 0;
  let failed = 0;
  let unverified = 0;
  const unverifiedList = [];
  list.forEach((r) => {
    const ok = !!(r && r.ok);
    const why = (r && typeof r.unverified === 'string' && r.unverified) ? r.unverified : null;
    if (ok && why) {
      unverified++;
      unverifiedList.push(why);
      if (strict) failed++;      // 严格档：未验证**按失败计**（不再有"两个数都不进"的第三档）
      return;                    // 默认档：不计入通过/总数（见上面口径）
    }
    if (ok) { passed++; return; }
    failed++;                                                            // fail-safe：ok:false 一律算失败
  });
  return { passed: passed, failed: failed, unverified: unverified, total: passed + failed,
    unverifiedList: unverifiedList };
};

/* ================= 冒烟断言的**共用工具**（只放"每个域都要做、做错了会互相污染"的那件事） =================
 * `mm.closeDialogs(ctx)`：收干净**产品自己打开的模态**（`window.MMApp.closeAllDialogs`，唯一实现在
 * `renderer/app-actions.js`；渲染层侧一行 DOM 都不重复写 ✓）。
 *
 * 为什么必须有这么一个共用入口（它是本轮修的一个**真事故**的收口）：
 *   `MMApp.addNode()` / `addTopic()` 会**顺手打开**「编辑节点」模态（产品行为，没错），
 *   而冒烟里的"每域隔离"只还原**项目数据文件 + 重开项目** ⇒ DOM 模态**跨域存活**：
 *   域 16 的 `addNode` 留下的编辑框盖住画布 ⇒ 域 36/37（真鼠标输入 + `elementFromPoint`）
 *   连锁红 11 条（报文 `点不到 comp-net …→DIV.dialog-box`），而那两个文件一行都没改过 ✗。
 *   全量跑当时还绿，只是因为后面的域**各自顺手**擦桌子（12-dsh-drag 扫 `.overlay`、
 *   27-import-doc 点 `edit-cancel`）—— 五份拷贝、各写各的，于是必然有域漏掉（实测漏了 4 个）✗。
 *
 * 用法（**任何**动了 `addNode`/`addTopic` 的域都要在断言体结束前调一次，并把 `n` 写进报文）：
 *   const mm = require('../smoke-assertions.js');
 *   const cleaned = await mm.closeDialogs(ctx);     // → { n, names }
 * 框架侧对应的是 main.js 的"域开始的干净前置"（**那一层是判据**：有残留 ⇒ 该域判红并点名）——
 * 两者分工：域自己收尾（这里）；框架保证"谁没收尾"会被看见（main.js）。
 * ⚠️ 只收模态/浮层（`.overlay` 一族 + 命令面板 + 审计面板）；浮动详情框、选区块、大小锁
 *    是**另一类**状态，不在它的责任内（那些由各自的域收拾）。
 */
module.exports.closeDialogs = async function closeDialogs(ctx) {
  const raw = await ctx.exec('(function () { return (window.MMApp && window.MMApp.closeAllDialogs)'
    + ' ? window.MMApp.closeAllDialogs() : []; })()');
  const list = Array.isArray(raw) ? raw : [];
  return { n: list.length, names: list.map((d) => d && d.name).filter(Boolean) };
};

/* ================= G5 **逐域耗时台账** + 排行（2026-10-18 加） =================
 * 为什么非有不可：G5 一项占全链 **93%**，而链上**只有整步一个读数** —— "时间花在哪个域"从来没被量过。
 * 没有这份读数，"分层 / 抽样 / 拆分"只能凭感觉拆（`testing-for-ai` A2：先量再优化）。
 * 它与 `scripts/verify.js` 的逐**步**耗时表是同一件事的两层：那层说"G5 用了多久"，这层说"G5 里谁用的"。
 *
 * 分工照 `B6`（判定逻辑与 I/O 分开）：
 *   · `createTiming()` —— 一个**只有四个方法**的台账；不读时钟（时刻由调用方递进来）、不碰 fs。
 *   · `summarizeTiming()` / `formatTimingLines()` —— **纯函数**，可单测（`tests/smoke-timing.test.js`）。
 *
 * 三条刻意的口径（都会被读的人误解，所以写死在这里）：
 *   ① `boundaryMs` **单独记**：域边界那一跳（收残留 + 还原沙箱文件 + 重载项目）**不是**断言本身的开销，
 *      却随"跑几个域"线性增长 ⇒ 分层的收益必须把这一档算进去，不能只算断言耗时。
 *   ② `totalMs = boundaryMs + assertMs`（该域可归因耗时之和；不把域之间的空隙摊给它）。
 *   ③ 台账**只量不改判**：不参与任何判据、不影响退出码 —— 拿掉它不改变任何结论。
 */
module.exports.createTiming = function createTiming() {
  const rows = [];
  const byDomain = new Map();
  let cur = null;
  let boundaryMs = 0;
  const mk = (domain) => {
    let r = byDomain.get(domain);
    if (!r) {
      r = { domain: domain, assertions: 0, assertMs: 0, boundaryMs: 0, totalMs: 0 };
      byDomain.set(domain, r);
      rows.push(r);
    }
    return r;
  };
  const close = () => {
    if (!cur) return;
    const r = mk(cur);
    r.boundaryMs += boundaryMs > 0 ? boundaryMs : 0;
    r.totalMs = r.boundaryMs + r.assertMs;
    cur = null;
    boundaryMs = 0;
  };
  return {
    /** 进入一个新域（自动收口上一个域的账）。`now` 只为将来记墙钟留位，当前口径不用。 */
    beginDomain(domain, now) { close(); cur = domain; boundaryMs = 0; mk(domain); return now; },
    /** 域边界那一跳花了多久（收残留 + 隔离写回 + 重载） */
    endBoundary(ms) { if (cur && ms > 0) boundaryMs += ms; },
    /** 一条断言体花了多久（成功与 THREW 两条路径都要记 —— 否则"贵的域"会被漏掉） */
    addAssertion(domain, ms) {
      const r = mk(domain);
      r.assertions += 1;
      if (ms > 0) r.assertMs += ms;
      if (!cur) r.totalMs = r.boundaryMs + r.assertMs;
    },
    /** 收口最后一个域 */
    end() { close(); },
    rows() { return rows.map((r) => Object.assign({}, r)); }
  };
};

/**
 * 逐域耗时排行（**纯函数**）：把台账行整理成一张"谁最贵"的表。
 * @param {Array<{domain:string,assertions:number,assertMs:number,boundaryMs:number}>} rows
 * @param {{topN?:number}} [opts] `topN` 只影响 `top`（`rank` 永远全量 —— 只报"前 N 名"而藏起其余 = 假口径）
 * @returns {{count:number, assertions:number, domainMs:number, boundaryMs:number, assertMs:number,
 *   rank:Array<{domain:string,assertions:number,assertMs:number,boundaryMs:number,totalMs:number,share:number}>,
 *   top:Array, topMs:number, topShare:number}}
 *   `share` = 该域占**全部域耗时**的比例（0–1；分母是 `domainMs`，**不含**启动 / 截图 / 收尾 —— 那几段不在本台账里）。
 */
module.exports.summarizeTiming = function summarizeTiming(rows, opts) {
  const o = opts || {};
  const list = (Array.isArray(rows) ? rows : []).filter(Boolean);
  const norm = list.map((r) => {
    const assertMs = Math.max(0, Number(r.assertMs) || 0);
    const boundaryMs = Math.max(0, Number(r.boundaryMs) || 0);
    return {
      domain: String(r.domain || '(未命名域)'),
      assertions: Math.max(0, Number(r.assertions) || 0),
      assertMs: assertMs,
      boundaryMs: boundaryMs,
      totalMs: assertMs + boundaryMs,
      share: 0
    };
  });
  const domainMs = norm.reduce((n, r) => n + r.totalMs, 0);
  // 降序；耗时相同按域名字典序 —— **读数是确定的**，同一份台账两次排出同一个名次（否则"排行"自己不可复现）
  norm.sort((a, b) => (b.totalMs - a.totalMs) || (a.domain < b.domain ? -1 : a.domain > b.domain ? 1 : 0));
  norm.forEach((r) => { r.share = domainMs > 0 ? r.totalMs / domainMs : 0; });
  const topN = Number.isInteger(o.topN) && o.topN > 0 ? o.topN : norm.length;
  const top = norm.slice(0, topN);
  const topMs = top.reduce((n, r) => n + r.totalMs, 0);
  return {
    count: norm.length,
    assertions: norm.reduce((n, r) => n + r.assertions, 0),
    domainMs: domainMs,
    boundaryMs: norm.reduce((n, r) => n + r.boundaryMs, 0),
    assertMs: norm.reduce((n, r) => n + r.assertMs, 0),
    rank: norm,
    top: top,
    topMs: topMs,
    topShare: domainMs > 0 ? topMs / domainMs : 0
  };
};

/**
 * 把排行渲染成**逐行文本**（纯函数：不打印、不判红，调用方决定去哪）。
 * @param {ReturnType<typeof summarizeTiming>} summary
 * @param {{tierOf?:(domain:string)=>string|null, title?:string}} [opts]
 *   `tierOf` 给了就在每行标出该域所属的分层（分层表是单一权威，本函数不复制它）
 * @returns {string[]}
 */
module.exports.formatTimingLines = function formatTimingLines(summary, opts) {
  const s = summary || { rank: [], domainMs: 0, assertions: 0, boundaryMs: 0, assertMs: 0, count: 0 };
  const o = opts || {};
  const sec = (ms) => (Math.round((Number(ms) || 0) / 100) / 10).toFixed(1) + 's';
  const pct = (x) => (Math.round((Number(x) || 0) * 1000) / 10).toFixed(1) + '%';
  const lines = [];
  lines.push(o.title || '==== G5 逐域耗时排行（现算；域 = scripts/smoke/NN-*.js）====');
  if (!s.rank.length) {
    lines.push('  （台账是空的：本轮一个域都没跑 —— 这不是"很快"，是**没有读数** ✗）');
    return lines;
  }
  lines.push('  名次  域                       耗时      占比    断言  断言均值  域边界'
    + (o.tierOf ? '  分层' : ''));
  s.rank.forEach((r, i) => {
    const avg = r.assertions > 0 ? r.assertMs / r.assertions : 0;
    const tier = o.tierOf ? (o.tierOf(r.domain) || '—') : null;
    lines.push('  ' + String(i + 1).padEnd(5)
      + String(r.domain).padEnd(24)
      + sec(r.totalMs).padStart(8)
      + pct(r.share).padStart(8)
      + String(r.assertions).padStart(6)
      + sec(avg).padStart(9)
      + sec(r.boundaryMs).padStart(8)
      + (o.tierOf ? '  ' + tier : ''));
  });
  lines.push('  ' + '合计（域 ' + s.count + ' 个）'.padEnd(28) + sec(s.domainMs).padStart(8)
    + '  100.0%' + String(s.assertions).padStart(7)
    + '         ' + sec(s.boundaryMs).padStart(8));
  lines.push('  口径：域耗时 = 断言体耗时 + 域边界那一跳（收残留 + 还原沙箱 + 重载项目）；'
    + '**不含**启动 / 截图 / 视觉断言 / 收尾 —— 那几段不在本台账里。');
  return lines;
};

