/* ============================================================
 * scripts/vision/thresholds.js — 视觉断言的**唯一阈值来源**
 * ------------------------------------------------------------
 * **存在的唯一理由**：纪律「**阈值单源**」 —— 一个 `thresholds.js`，禁止各断言各写一套。
 * 起因是真实的：本工程的"有效帧"阈值原先内联在 `scripts/smoke/14-headless-window.js` 的
 * 一条断言里，一旦要加第二条视觉断言（L2 ROI），就会出现"两处各有一套阈值"，
 * 于是**调了 A 不知道 B 还在用旧值** —— 这类漂移不会报错，只会让判别力悄悄变弱。
 *
 * 口径来源：**本工程自己的实测标定**（`validFrame` / `roi` / `sampleCap` 三项）；三级判据
 * （L1 有效帧 / L2 关键区域 / L3 基线差率）的落地状态与偏离见 `docs/ARCHITECTURE.md` §4b 的 ADR。
 * `validFrame` 的三项与工程原先内联的值**逐字相同** ⇒ 抽出本文件**不改变任何既有行为**。
 *
 * ⚠️ 判别力的现实依据（实测）：真实界面帧 `unique` 数百、`range≈225`、`variance≈4000`；
 * 全黑/全白帧 `unique=1 / range=0` ⇒ 与下面的阈值差**一两个数量级**，余量充足。
 *
 * ⚠️ **本文件不含 L3（基线差率）的键** —— 该层按评估结论**本阶段不做**（需人确认基线 + 需新增
 * `.raw` 产物形态 + 无真实回归事故为据，见 `.review/20260926-静默闭环2-5/01-逐阶段评估-定稿.md` §4）。
 * 落地 L3 时再在此处加 `baseline` 键，**不要**在各断言里散写。
 * ============================================================ */
'use strict';

module.exports = Object.freeze({
  /** L1「有效帧」：非空、非纯色。整图判据。 */
  validFrame: Object.freeze({ minUnique: 8, minRange: 40, minVariance: 4 }),

  /** L2「ROI」：关键区域独立统计。阈值比整图松（区域小、像素少）。 */
  roi: Object.freeze({ minUnique: 4, minRange: 24, minVariance: 2 }),

  /** 采样上限（像素点）—— 统计是采样的，不是全量的，防止大图拖慢冒烟。 */
  sampleCap: 20000,

  /** 「强调色描边**真的画出来了**」的判据（真输入域的 Ctrl+加选虚线描边 / 大虚线框）。
   *
   *  为什么需要它：只读 `getComputedStyle` 的 `outline-style === 'dashed'` 是**代用品**证据 ——
   *  规则命中、样式算得出来，但**画面上可能什么都没有**（被祖先 overflow 裁掉、被别的元素盖住、
   *  颜色被改成透明、GPU 帧没更新）。像素才是"看得到"的直接证据 ✓。
   *
   *  通道序无关（与 `frame-stats.js` 文件头那条契约一致）：只对**排序后**的三元组判
   *  `(min, mid, max)` —— 本工程强调色 `#1664ff` 排序后是 `(22,100,255)` ✓ 任何通道排列都命中同一个判据。
   *  取值的余量（按 `#1664ff` 的 min=22 / mid=100 / max=255 标定）：
   *    · `maxMin:100` 放得过 22，但把"浅灰/白底"（三元组差值≈0）与"浅色混合"（min>100）挡在外面；
   *    · `minMid:35` 是为挡住**纯红**（排序后 mid≈0）—— 否则红与蓝在"只看 min/max"时无法区分；
   *    · `maxMid:180` 是上限那侧的同款考虑。
   *  数字只此一份：判定函数不写数字（`tests/frame-stats.test.js` 锁这一条）。 */
  dashStroke: Object.freeze({
    minMax: 180, maxMin: 100, minMid: 35, maxMid: 180,
    /** 一圈 2px 虚线描边上"够饱和的蓝"至少该命中这么多像素（实测一整圈是数百） */
    minHits: 20,
    /** 「描边是**虚线**而不是实线」的判据：单行里连续命中像素的最大长度（实测虚线为 6~7px；
     *  改成实线会立刻跳到节点宽度量级（上百 px）⇒ 24 既能容纳抗锯齿，又抓得住"悄悄改成实线"✓ */
    maxRun: 24,
    /** 「**没有**那个大虚线框」的判据：把"大框上边沿应该在的那条横带"整条扫一遍，
     *  命中的饱和蓝像素必须少于此值。大框宽 ≥300px、虚线约占一半 ⇒ 真画出来是数百命中；
     *  24 留了约 6 倍余量（够容纳抗锯齿与别的节点蹭进来的零星像素）✓ */
    maxBoxHits: 24
  })
});
